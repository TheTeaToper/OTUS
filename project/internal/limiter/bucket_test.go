package limiter

import "testing"

func TestBucket_RateLimiting(t *testing.T) {
	// Создаем бакет: 3 запроса в минуту
	b := NewBucket(3)

	// 1-3 запросы должны пройти успешно
	for i := 1; i <= 3; i++ {
		if !b.Allow() {
			t.Fatalf("Запрос %d должен был пройти успешно", i)
		}
	}

	// 4-й запрос подряд должен заблокироваться
	if b.Allow() {
		t.Fatal("4-й запрос подряд должен быть заблокирован лимитером")
	}

	// Сбрасываем бакет вручную
	b.Reset()

	// После сброса запрос снова должен пройти
	if !b.Allow() {
		t.Fatal("После сброса бакета запрос должен быть разрешен")
	}
}
